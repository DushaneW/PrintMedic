class _SafeDict(dict[str, str]):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def render(code: str, lang: str, params: dict[str, str]) -> E:
    entry = CATALOG.get(code, {})
    data = entry.get(lang) or entry.get("en") or dict(title=code, causes=[], steps=[], verify="", limits="")
    p = _SafeDict(params)

    def fmt(v: Any) -> Any:
        if isinstance(v, str):
            return v.format_map(p)
        if isinstance(v, list):
            return [fmt(x) for x in v]
        return v

    return {k: fmt(v) for k, v in data.items()}
